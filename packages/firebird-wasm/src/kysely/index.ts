/**
 * firebird-wasm/kysely – a Kysely dialect for `FirebirdBrowser` and `FirebirdLite`.
 *
 * ```ts
 * import { Kysely } from 'kysely';
 * import type { Generated } from 'kysely';
 * import { FirebirdDialect, createKysely } from 'firebird-wasm/kysely';
 *
 * interface Database {
 *   items: {
 *     id: Generated<number>;
 *     title: string;
 *     done: boolean;
 *   };
 * }
 *
 * const db = createKysely<Database>(fb);
 * // or: new Kysely<Database>({ dialect: new FirebirdDialect({ database: fb }) });
 *
 * const rows = await db
 *   .selectFrom('items')
 *   .select(['id', 'title', 'done'])
 *   .where('done', '=', false)
 *   .orderBy('id')
 *   .offset(10)
 *   .limit(5)
 *   .execute();
 * ```
 *
 * Compiles to Firebird 3+ SQL:
 * - `?` positional parameter placeholders;
 * - `OFFSET ? ROWS FETCH NEXT ? ROWS ONLY` pagination (and `ROWS ?` on `UPDATE`/`DELETE`);
 * - `INSERT / UPDATE / DELETE … RETURNING`;
 * - `UPDATE OR INSERT INTO … MATCHING (…)` on `.onConflict(oc => oc.column(…).doUpdateSet(…))`;
 * - multi-row `INSERT INTO … SELECT … FROM RDB$DATABASE UNION ALL …`;
 * - `GENERATED BY DEFAULT AS IDENTITY` for `autoIncrement` / `serial` / `bigserial`;
 * - bijective identifier folding (`items` ↔ `"ITEMS"`, while `"camelCase"` stays `"camelCase"`),
 *   so lowercase Kysely table/column types work out of the box against unquoted Firebird DDL.
 */

