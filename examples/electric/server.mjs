// The example's server: the page, two shape sources, and a small write API.
//
//   node server.mjs [--isolated]
//
// GET  /electric/v1/shape        Electric's shapes of the Postgres database (proxied)
// GET  /firebird/v1/shape        the Firebird server's, from firebird-wasm/electric-server
// POST /api/{pg|fb}/notes        {"title": "…"}: add a note at the source
// POST /api/{pg|fb}/notes/<id>/toggle
// DELETE /api/{pg|fb}/notes/<id>
// anything else                  the built page, from dist/
//
// The page never writes to its own copy: it asks this server to write to the
// source, and the change comes back down the shape. That is the read path
// firebird-wasm/electric gives today (see the README).
//
// Configuration, with the defaults docker-compose.yml matches:
//   PORT=4190
//   PG_URL=postgresql://postgres:pg@localhost:54321/postgres
//   ELECTRIC_URL=http://localhost:3000
//   FIREBIRD_DATABASE=localhost:/tmp/electric-example.fdb   (a path on the Firebird server)
//   FIREBIRD_USER=SYSDBA  FIREBIRD_PASSWORD=masterkey
import * as fs from 'node:fs';
import * as http from 'node:http';
import * as path from 'node:path';
import { Readable } from 'node:stream';
import { fileURLToPath } from 'node:url';
import pg from 'pg';
import { FirebirdLite } from 'firebird-wasm';
import { createShapeServer } from 'firebird-wasm/electric-server';

const env = process.env;
const PORT = Number(env.PORT ?? 4190);
const PG_URL = env.PG_URL ?? 'postgresql://postgres:pg@localhost:54321/postgres';
const ELECTRIC_URL = (env.ELECTRIC_URL ?? 'http://localhost:3000').replace(/\/$/, '');
const FIREBIRD_DATABASE = env.FIREBIRD_DATABASE ?? 'localhost:/tmp/electric-example.fdb';
const credentials = { username: env.FIREBIRD_USER ?? 'SYSDBA', password: env.FIREBIRD_PASSWORD ?? 'masterkey' };
const isolated = process.argv.includes('--isolated');
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), 'dist');

// ── The sources ────────────────────────────────────────────────────────────

const postgres = new pg.Pool({ connectionString: PG_URL });
await postgres.query(`CREATE TABLE IF NOT EXISTS notes (
  id BIGSERIAL PRIMARY KEY,
  title TEXT NOT NULL,
  done BOOLEAN NOT NULL DEFAULT false,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
)`).catch((err) => {
  // Two servers starting at once can both get past IF NOT EXISTS; the loser
  // finds the table (42P07) or its type (23505) made, which is what it wanted.
  if (err.code !== '42P07' && err.code !== '23505') throw err;
});

// Created on the Firebird server if it does not exist.
const firebird = new FirebirdLite(FIREBIRD_DATABASE, credentials);
const { rows: existing } = await firebird.query(
  "SELECT COUNT(*) AS N FROM rdb$relations WHERE rdb$relation_name = 'NOTES'");
if (Number(existing[0].N) === 0) {
  await firebird.exec(`CREATE TABLE notes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    done BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
  )`);
}
const shapes = await createShapeServer({ database: FIREBIRD_DATABASE, ...credentials, tables: ['notes'] });

const write = {
  pg: {
    add: (title) => postgres.query('INSERT INTO notes (title) VALUES ($1)', [title]),
    toggle: (id) => postgres.query('UPDATE notes SET done = NOT done WHERE id = $1', [id]),
    remove: (id) => postgres.query('DELETE FROM notes WHERE id = $1', [id]),
  },
  fb: {
    add: (title) => firebird.exec('INSERT INTO notes (title) VALUES (?)', [title]),
    toggle: (id) => firebird.exec('UPDATE notes SET done = NOT done WHERE id = ?', [id]),
    remove: (id) => firebird.exec('DELETE FROM notes WHERE id = ?', [id]),
  },
};

// ── HTTP ───────────────────────────────────────────────────────────────────

const TYPES = {
  '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css',
  '.wasm': 'application/wasm', '.json': 'application/json',
};

function send(res, status, body) {
  res.writeHead(status, { 'content-type': 'application/json' });
  res.end(JSON.stringify(body));
}

async function readJson(req) {
  let text = '';
  for await (const chunk of req) {
    text += chunk;
    if (text.length > 10_000) throw Object.assign(new Error('body too large'), { status: 413 });
  }
  return text ? JSON.parse(text) : {};
}

/** Electric, on this origin: the query string as given, the response as it came. */
async function proxyElectric(req, res, url) {
  const abort = new AbortController();
  res.on('close', () => abort.abort());
  const upstream = await fetch(`${ELECTRIC_URL}/v1/shape${url.search}`, { signal: abort.signal });
  const headers = {};
  upstream.headers.forEach((value, name) => {
    // fetch has already decoded the body and knows nothing of its framing.
    if (!['content-encoding', 'content-length', 'transfer-encoding', 'connection'].includes(name)) headers[name] = value;
  });
  res.writeHead(upstream.status, headers);
  if (upstream.body) Readable.fromWeb(upstream.body).on('error', () => res.destroy()).pipe(res);
  else res.end();
}

async function api(req, res, url) {
  const match = url.pathname.match(/^\/api\/(pg|fb)\/notes(?:\/(\d+)(\/toggle)?)?$/);
  if (!match) return send(res, 404, { error: 'not found' });
  const [, source, id, toggle] = match;
  const to = write[source];
  if (req.method === 'POST' && !id) {
    const { title } = await readJson(req);
    if (typeof title !== 'string' || !title.trim() || title.length > 200) {
      return send(res, 400, { error: 'title: 1 to 200 characters' });
    }
    await to.add(title.trim());
  } else if (req.method === 'POST' && id && toggle) {
    await to.toggle(Number(id));
  } else if (req.method === 'DELETE' && id && !toggle) {
    await to.remove(Number(id));
  } else {
    return send(res, 405, { error: 'method not allowed' });
  }
  send(res, 200, { ok: true });
}

function serveFile(req, res, url) {
  const file = path.join(root, url.pathname === '/' ? 'index.html' : decodeURIComponent(url.pathname));
  if (!file.startsWith(root + path.sep) || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
    res.writeHead(404);
    res.end(fs.existsSync(root) ? 'not found' : 'dist/ is missing: run npm run build first');
    return;
  }
  const headers = { 'content-type': TYPES[path.extname(file)] ?? 'application/octet-stream' };
  if (isolated) {
    headers['cross-origin-opener-policy'] = 'same-origin';
    headers['cross-origin-embedder-policy'] = 'require-corp';
  }
  res.writeHead(200, headers);
  fs.createReadStream(file).pipe(res);
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url ?? '/', 'http://localhost');
  try {
    if (url.pathname === '/electric/v1/shape') return await proxyElectric(req, res, url);
    if (url.pathname === '/firebird/v1/shape') {
      req.url = '/v1/shape' + url.search;
      return shapes.handler(req, res);
    }
    if (url.pathname.startsWith('/api/')) return await api(req, res, url);
    serveFile(req, res, url);
  } catch (err) {
    if (res.headersSent) return res.destroy();
    send(res, err.status ?? 500, { error: String(err.message ?? err) });
  }
});
server.listen(PORT, () => {
  console.log(`http://localhost:${PORT}/${isolated ? ' (cross-origin isolated)' : ''}`);
  console.log(`  Postgres ${PG_URL.replace(/:[^:@/]+@/, ':…@')} through Electric at ${ELECTRIC_URL}`);
  console.log(`  Firebird ${FIREBIRD_DATABASE}`);
});

async function stop() {
  server.closeAllConnections?.();
  server.close();
  await shapes.close();
  await firebird.close();
  await postgres.end();
  process.exit(0);
}
process.on('SIGINT', stop);
process.on('SIGTERM', stop);
